local M = { DATA = DB }

local function pick_lvl(v, lvl)
  if type(v) == "table" then
    local idx = math.max(1, math.min(#v, math.floor(lvl or 1)))
    return v[idx]
  end
  return v
end

function M.get(name)
  return DB[name]
end

function M.get_delay(name, lvl)
  local e = DB[name]
  return e and pick_lvl(e.delay, lvl) or 0
end

function M.get_lift(name, lvl)
  local e = DB[name]
  return e and pick_lvl(e.lift, lvl) or 0
end

function M.get_range(name, lvl, cast_bonus)
  local e = DB[name]
  local base = e and pick_lvl(e.range, lvl) or 0
  if base <= 0 then return 0 end
  return base + (cast_bonus or 0)
end

function M.get_cast_point(name)
  local e = DB[name]
  return (e and e.cp) or 0
end

function M.get_speed(name, lvl)
  local e = DB[name]
  return e and pick_lvl(e.speed, lvl) or 0
end

function M.get_aoe(name, lvl)
  local e = DB[name]
  return e and pick_lvl(e.aoe, lvl) or 0
end

function M.pierces_bkb(name)
  local e = DB[name]
  return e ~= nil and e.bkb == true
end

return M
